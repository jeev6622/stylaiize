/**
 * Search mock products with filtering, sorting, and pagination.
 */
export function searchMockProducts(
  query: string,
  options: {
    category?: string;
    minPrice?: number;
    maxPrice?: number;
    sortBy?: string;
    page?: number;
    limit?: number;
  } = {},
): {
  products: Product[];
  total: number;
  page: number;
  totalPages: number;
} {
  const {
    category,
    minPrice,
    maxPrice,
    sortBy = "relevance",
    page = 1,
    limit = 12,
  } = options;

  const queryLower = query.toLowerCase();
  const queryWords = queryLower.split(/\s+/).filter(Boolean);

  const filtered = MOCK_PRODUCTS.filter((p) => {
    const searchText = `${p.title} ${p.brand ?? ""} ${p.category}`.toLowerCase();
    const matchesQuery = queryWords.every((word) => searchText.includes(word));
    if (!matchesQuery) return false;

    if (category && p.category.toLowerCase() !== category.toLowerCase()) {
      return false;
    }
    if (minPrice !== undefined && p.price < minPrice) return false;
    if (maxPrice !== undefined && p.price > maxPrice) return false;

    return true;
  });

  switch (sortBy) {
    case "price_asc":
      filtered.sort((a, b) => a.price - b.price);
      break;
    case "price_desc":
      filtered.sort((a, b) => b.price - a.price);
      break;
    case "rating":
      filtered.sort((a, b) => (b.rating ?? 0) - (a.rating ?? 0));
      break;
    case "discount":
      filtered.sort(
        (a, b) => (b.discountPercent ?? 0) - (a.discountPercent ?? 0),
      );
      break;
    default:
      break;
  }

  const total = filtered.length;
  const totalPages = Math.max(1, Math.ceil(total / limit));
  const safePage = Math.min(page, totalPages);
  const start = (safePage - 1) * limit;
  const products = filtered.slice(start, start + limit);

  return { products, total, page: safePage, totalPages };
}
